pub fn language_spec(lang: LanguageId) -> LanguageSpec {
    match lang {
        LanguageId::Rust => LanguageSpec {
            line_comment: Some("//"),
            hash_comment: false,
            block_comment: Some(("/*", "*/")),
            nested_block_comments: true,
            backtick_strings: false,
            triple_quotes: false,
            keywords: RUST_KW,
            types: RUST_TYPES,
            constants: COMMON_CONSTS,
        },
        LanguageId::TypeScript | LanguageId::Tsx | LanguageId::JavaScript => LanguageSpec {
            line_comment: Some("//"),
            hash_comment: false,
            block_comment: Some(("/*", "*/")),
            nested_block_comments: false,
            backtick_strings: true,
            triple_quotes: false,
            keywords: JS_KW,
            types: JS_TYPES,
            constants: COMMON_CONSTS,
        },
        LanguageId::Python => LanguageSpec {
            line_comment: None,
            hash_comment: true,
            block_comment: None,
            nested_block_comments: false,
            backtick_strings: false,
            triple_quotes: true,
            keywords: PY_KW,
            types: PY_TYPES,
            constants: COMMON_CONSTS,
        },
        LanguageId::Go => LanguageSpec {
            line_comment: Some("//"),
            hash_comment: false,
            block_comment: Some(("/*", "*/")),
            nested_block_comments: false,
            backtick_strings: true,
            triple_quotes: false,
            keywords: GO_KW,
            types: GO_TYPES,
            constants: COMMON_CONSTS,
        },
        LanguageId::C | LanguageId::Cpp | LanguageId::Zig => LanguageSpec {
            line_comment: Some("//"),
            hash_comment: false,
            block_comment: Some(("/*", "*/")),
            nested_block_comments: false,
            backtick_strings: false,
            triple_quotes: false,
            keywords: C_KW,
            types: C_TYPES,
            constants: COMMON_CONSTS,
        },
        LanguageId::Java
        | LanguageId::Kotlin
        | LanguageId::Swift
        | LanguageId::CSharp
        | LanguageId::Php => LanguageSpec {
            line_comment: Some("//"),
            hash_comment: matches!(lang, LanguageId::Php),
            block_comment: Some(("/*", "*/")),
            nested_block_comments: matches!(lang, LanguageId::Swift | LanguageId::Kotlin),
            backtick_strings: false,
            triple_quotes: matches!(lang, LanguageId::Kotlin | LanguageId::Swift),
            keywords: JVM_KW,
            types: RUST_TYPES,
            constants: COMMON_CONSTS,
        },
        LanguageId::Shell | LanguageId::Ruby => LanguageSpec {
            line_comment: None,
            hash_comment: true,
            block_comment: None,
            nested_block_comments: false,
            backtick_strings: true,
            triple_quotes: false,
            keywords: SH_KW,
            types: &[],
            constants: COMMON_CONSTS,
        },
        LanguageId::Sql => LanguageSpec {
            line_comment: Some("--"),
            hash_comment: false,
            block_comment: Some(("/*", "*/")),
            nested_block_comments: false,
            backtick_strings: false,
            triple_quotes: false,
            keywords: SQL_KW,
            types: &["INT", "TEXT", "VARCHAR", "BOOLEAN", "TIMESTAMP", "JSONB"],
            constants: COMMON_CONSTS,
        },
        LanguageId::Lua => LanguageSpec {
            line_comment: Some("--"),
            hash_comment: false,
            block_comment: Some(("--[[", "]]")),
            nested_block_comments: false,
            backtick_strings: false,
            triple_quotes: false,
            keywords: &[
                "and", "break", "do", "else", "elseif", "end", "for", "function", "if", "in",
                "local", "not", "or", "repeat", "return", "then", "until", "while",
            ],
            types: &[],
            constants: COMMON_CONSTS,
        },
        LanguageId::Mermaid => LanguageSpec {
            line_comment: Some("%%"),
            hash_comment: false,
            block_comment: None,
            nested_block_comments: false,
            backtick_strings: false,
            triple_quotes: false,
            keywords: MERMAID_KW,
            types: &[],
            constants: &[],
        },
        LanguageId::Graphql => LanguageSpec {
            line_comment: None,
            hash_comment: true,
            block_comment: None,
            nested_block_comments: false,
            backtick_strings: false,
            triple_quotes: true,
            keywords: GQL_KW,
            types: &["Int", "Float", "String", "Boolean", "ID"],
            constants: COMMON_CONSTS,
        },
        LanguageId::Dockerfile => LanguageSpec {
            line_comment: None,
            hash_comment: true,
            block_comment: None,
            nested_block_comments: false,
            backtick_strings: false,
            triple_quotes: false,
            keywords: DOCKER_KW,
            types: &[],
            constants: &[],
        },
        LanguageId::Json | LanguageId::Yaml | LanguageId::Toml => LanguageSpec {
            line_comment: None,
            hash_comment: !matches!(lang, LanguageId::Json),
            block_comment: None,
            nested_block_comments: false,
            backtick_strings: false,
            triple_quotes: matches!(lang, LanguageId::Toml),
            keywords: &[],
            types: &[],
            constants: COMMON_CONSTS,
        },
        LanguageId::Css => LanguageSpec {
            line_comment: Some("//"),
            hash_comment: false,
            block_comment: Some(("/*", "*/")),
            nested_block_comments: false,
            backtick_strings: false,
            triple_quotes: false,
            keywords: &[
                "@media",
                "@import",
                "@keyframes",
                "@supports",
                "@layer",
                "!important",
            ],
            types: &[],
            constants: &[
                "none", "auto", "inherit", "initial", "flex", "grid", "block",
            ],
        },
        LanguageId::Typst => LanguageSpec {
            line_comment: Some("//"),
            hash_comment: false,
            block_comment: Some(("/*", "*/")),
            nested_block_comments: true,
            backtick_strings: true,
            triple_quotes: false,
            keywords: &[
                "let", "set", "show", "import", "include", "if", "else", "for", "in", "while",
                "return", "break", "continue",
            ],
            types: &[],
            constants: COMMON_CONSTS,
        },
        LanguageId::Html
        | LanguageId::Markdown
        | LanguageId::Latex
        | LanguageId::Diff
        | LanguageId::Plain => LanguageSpec {
            line_comment: None,
            hash_comment: false,
            block_comment: None,
            nested_block_comments: false,
            backtick_strings: false,
            triple_quotes: false,
            keywords: &[],
            types: &[],
            constants: &[],
        },
    }
}
