/// Supported language families for the pure-Rust syntax highlighter.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum LanguageId {
    Plain,
    Rust,
    TypeScript,
    Tsx,
    JavaScript,
    Python,
    Go,
    C,
    Cpp,
    Java,
    Kotlin,
    Swift,
    Shell,
    Json,
    Yaml,
    Toml,
    Sql,
    Html,
    Css,
    Markdown,
    Latex,
    Typst,
    Mermaid,
    Graphql,
    Dockerfile,
    Diff,
    Ruby,
    Php,
    CSharp,
    Lua,
    Zig,
}

/// Static lexer configuration for one language family.
#[derive(Clone, Copy, Debug)]
pub struct LanguageSpec {
    pub line_comment: Option<&'static str>,
    pub hash_comment: bool,
    pub block_comment: Option<(&'static str, &'static str)>,
    pub nested_block_comments: bool,
    pub backtick_strings: bool,
    pub triple_quotes: bool,
    pub keywords: &'static [&'static str],
    pub types: &'static [&'static str],
    pub constants: &'static [&'static str],
}

/// Resolve a language identifier or alias (case-insensitive) to a [`LanguageId`].
pub fn resolve_language(raw: &str) -> LanguageId {
    match raw.trim().to_ascii_lowercase().as_str() {
        "rs" | "rust" => LanguageId::Rust,
        "ts" | "typescript" | "mts" | "cts" => LanguageId::TypeScript,
        "tsx" => LanguageId::Tsx,
        "js" | "javascript" | "mjs" | "cjs" | "jsx" => LanguageId::JavaScript,
        "py" | "python" | "py3" => LanguageId::Python,
        "go" | "golang" => LanguageId::Go,
        "c" | "h" => LanguageId::C,
        "cpp" | "c++" | "cc" | "cxx" | "hpp" | "hh" => LanguageId::Cpp,
        "java" => LanguageId::Java,
        "kt" | "kts" | "kotlin" => LanguageId::Kotlin,
        "swift" => LanguageId::Swift,
        "sh" | "bash" | "zsh" | "shell" | "fish" => LanguageId::Shell,
        "json" | "jsonc" | "json5" => LanguageId::Json,
        "yaml" | "yml" => LanguageId::Yaml,
        "toml" => LanguageId::Toml,
        "sql" | "postgres" | "postgresql" | "sqlite" | "mysql" => LanguageId::Sql,
        "html" | "htm" | "xml" | "svg" => LanguageId::Html,
        "css" | "scss" | "sass" | "less" => LanguageId::Css,
        "md" | "markdown" | "mdx" => LanguageId::Markdown,
        "latex" | "tex" | "math" => LanguageId::Latex,
        "typst" | "typ" => LanguageId::Typst,
        "mermaid" | "mmd" => LanguageId::Mermaid,
        "graphql" | "gql" => LanguageId::Graphql,
        "dockerfile" | "docker" => LanguageId::Dockerfile,
        "diff" | "patch" => LanguageId::Diff,
        "rb" | "ruby" => LanguageId::Ruby,
        "php" => LanguageId::Php,
        "cs" | "csharp" | "c#" => LanguageId::CSharp,
        "lua" => LanguageId::Lua,
        "zig" => LanguageId::Zig,
        _ => LanguageId::Plain,
    }
}

